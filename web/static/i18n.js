let currentLang = localStorage.getItem("hsk5_lang") || "ru";

function t(key) {
  return (STRINGS[currentLang] && STRINGS[currentLang][key]) || key;
}

function setLang(code) {
  if (STRINGS[code]) {
    currentLang = code;
    localStorage.setItem("hsk5_lang", code);
    window.dispatchEvent(new Event("lang_changed"));
  }
}

function getLang() {
  return currentLang;
}
