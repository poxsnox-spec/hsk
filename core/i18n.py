class I18n:
    """Менеджер локализации. Хранит текущий язык и предоставляет перевод."""

    def __init__(self, lang: str = DEFAULT_LANGUAGE):
        self._listeners = []
        self.set_language(lang)

    def set_language(self, lang: str):
        if lang not in ("ru", "tk", "en", "uz", "tg"):
            lang = DEFAULT_LANGUAGE
        self._lang = lang
        self._notify()

    @property
    def language(self) -> str:
        return self._lang

    def t(self, key: str) -> str:
        entry = STRINGS.get(key)
        if entry is None:
            return f"[{key}]"
        return entry.get(self._lang) or entry.get("en", f"[{key}]")

    def subscribe(self, callback):
        self._listeners.append(callback)

    def _notify(self):
        for cb in self._listeners:
            try:
                cb()
            except Exception as e:
                print(f"[i18n] listener error: {e}")


